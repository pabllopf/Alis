using System;
using Alis.Core.Aspect.Math.Vector;
using Alis.Extension.Graphic.Sfml.Test.Attributes;
using Alis.Extension.Graphic.Sfml.Windows;
using Xunit;

namespace Alis.Extension.Graphic.Sfml.Test.Windows
{
    /// <summary>
    ///     The cursor pixel constructor tests class
    /// </summary>
    public class CursorPixelConstructorTests
    {
        /// <summary>
        ///     Tests that the pixel constructor with null pixels does not throw and keeps the pointer zero
        /// </summary>
        [RequireCSfmlWindowsFact]
        public void Constructor_WithNullPixels_ReturnsZeroPointer()
        {
            using Cursor cursor = new Cursor(null, new Vector2F(1, 1), new Vector2F(0, 0));

            Assert.Equal(IntPtr.Zero, cursor.CPointer);
        }
    }
}
